def verify_commutation(code):
    """
    Verifies that all stabilizer generators pairwise commute:
    A B^T + B A^T = 0 (mod 2)
    """
    S = code.to_binary_symplectic()
    n = code.n
    A = S[:, :n]
    B = S[:, n:]
    comm = (A @ B.T + B @ A.T) % 2
    return np.all(comm == 0)


def exhaustive_distance_search(code, max_weight=3):
    """
    Exhaustively searches for any non-trivial Pauli logical operator of weight <= max_weight.
    Returns (min_weight, witness_dict) or None if no logical exists up to max_weight.
    """
    S = code.to_binary_symplectic()
    m, n2 = S.shape
    n = code.n
    A = S[:, :n]
    B = S[:, n:]

    # Syndrome of a Pauli vector p = (x | z) is: S_comm(p) = (B @ x + A @ z) % 2
    # A Pauli is in the stabilizer group or centralizer if syndrome is zero.
    # It is non-trivial if it anticommutes with at least one generator or cannot be generated by S.
    import itertools

    for w in range(1, max_weight + 1):
        for qubits in itertools.combinations(range(n), w):
            # 3^w non-identity Pauli combinations on these qubits
            for paulis in itertools.product([(1, 0), (0, 1), (1, 1)], repeat=w):
                x = np.zeros(n, dtype=np.uint8)
                z = np.zeros(n, dtype=np.uint8)
                for q, (px, pz) in zip(qubits, paulis):
                    x[q] = px
                    z[q] = pz
                
                # Check syndrome: B x + A z mod 2
                syn = (B @ x + A @ z) % 2
                if np.all(syn == 0):
                    # Commutes with all stabilizers. Check if it is in the stabilizer group.
                    # Build aug matrix [S^T | (x, z)^T]
                    aug = np.column_stack([S.T, np.concatenate([x, z])])
                    # rank check over GF(2)
                    r_S = _gf2_rank(S.T)
                    r_aug = _gf2_rank(aug)
                    if r_aug > r_S:
                        # Non-trivial logical found!
                        x_idx = [int(q) for q in range(n) if x[q]]
                        z_idx = [int(q) for q in range(n) if z[q]]
                        return w, {"X": x_idx, "Z": z_idx}
    return None


