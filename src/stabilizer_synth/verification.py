def _gf2_rank(mat):
    """Gaussian elimination over GF(2) returning matrix rank."""
    A = mat.copy() % 2
    rows, cols = A.shape
    rank = 0
    for c in range(cols):
        pivot = None
        for r in range(rank, rows):
            if A[r, c] == 1:
                pivot = r
                break
        if pivot is not None:
            A[[rank, pivot]] = A[[pivot, rank]]
            for r in range(rows):
                if r != rank and A[r, c] == 1:
                    A[r] ^= A[rank]
            rank += 1
            if rank == rows:
                break
    return rank
